"""Accounts for Vouch: sign-up, log-in sessions, plans, Pro requests, each user's stored
profile, resume header and Pro builds.

Storage is SQLite by default (a file under .studio/, standard library) or Postgres when
given a postgres:// URL (for example Neon, through DATABASE_URL), which needs the
`psycopg` package that only the web layer installs. The SQL is written once with `?`
placeholders and runs on both.

Passwords are stored as salted scrypt hashes. A session token is random, lives in an
HttpOnly cookie, and only its SHA-256 is stored, so a copied database cannot be used to
log in. Everything an account uploads or builds belongs to that account alone and is
deleted with it. Nothing here reads the workspace's own master profile.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import os
import re
import secrets
import sqlite3
import threading
import time
from collections import deque
from pathlib import Path
from typing import Any, Callable, Iterable

SESSION_SECONDS = 30 * 24 * 3600
PASSWORD_MIN = 8
PASSWORD_MAX = 256
NAME_MAX = 80
EMAIL_MAX = 254
NOTE_MAX = 600
EMAIL = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")
SCRYPT_N, SCRYPT_R, SCRYPT_P = 2 ** 14, 8, 1
PLANS = ("basic", "pro")

_TABLES = """
CREATE TABLE IF NOT EXISTS users (
    id {id},
    email TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL DEFAULT '',
    password_hash TEXT NOT NULL,
    is_admin INTEGER NOT NULL DEFAULT 0,
    plan TEXT NOT NULL DEFAULT 'basic',
    created_at {real} NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at {real} NOT NULL,
    expires_at {real} NOT NULL
);
CREATE TABLE IF NOT EXISTS profiles (
    user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    content {blob} NOT NULL,
    sha256 TEXT NOT NULL,
    updated_at {real} NOT NULL
);
CREATE TABLE IF NOT EXISTS resume_headers (
    user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    header TEXT NOT NULL,
    updated_at {real} NOT NULL
);
CREATE TABLE IF NOT EXISTS pro_requests (
    id {id},
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    note TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'pending',
    created_at {real} NOT NULL,
    decided_at {real},
    decided_by INTEGER
);
CREATE TABLE IF NOT EXISTS builds (
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    job_id TEXT NOT NULL,
    title TEXT NOT NULL DEFAULT '',
    company TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL,
    summary TEXT NOT NULL,
    pdf {blob},
    report TEXT,
    created_at {real} NOT NULL,
    PRIMARY KEY (user_id, job_id)
);
"""
SQLITE_TYPES = {"id": "INTEGER PRIMARY KEY", "real": "REAL", "blob": "BLOB"}
POSTGRES_TYPES = {"id": "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                  "real": "DOUBLE PRECISION", "blob": "BYTEA"}
# Columns added after a table first shipped: (table, column, definition).
MIGRATIONS = (("users", "plan", "TEXT NOT NULL DEFAULT 'basic'"),)


class AccountError(Exception):
    """A request the account layer refuses; `status` is the HTTP status to answer with."""

    def __init__(self, status: int, message: str) -> None:
        super().__init__(message)
        self.status = status


def hash_password(password: str) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode("utf-8"), salt=salt, n=SCRYPT_N, r=SCRYPT_R,
                            p=SCRYPT_P, dklen=32)
    return f"scrypt${SCRYPT_N}${SCRYPT_R}${SCRYPT_P}${salt.hex()}${digest.hex()}"


def check_password(password: str, stored: str) -> bool:
    try:
        scheme, n, r, p, salt, digest = stored.split("$")
        if scheme != "scrypt":
            return False
        actual = hashlib.scrypt(password.encode("utf-8"), salt=bytes.fromhex(salt), n=int(n),
                                r=int(r), p=int(p), dklen=len(digest) // 2)
    except (ValueError, TypeError):
        return False
    return hmac.compare_digest(actual.hex(), digest)


def _token_hash(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def normalize_email(email: str) -> str:
    return (email or "").strip().lower()


def read_admin_emails(path: Path | None = None, env: dict[str, str] | None = None) -> frozenset[str]:
    """Emails that are admins as soon as they sign up: VOUCH_ADMIN_EMAILS (comma separated)
    plus one email per line of `path` (kept out of git, under .studio/)."""
    found = set()
    raw = (env if env is not None else os.environ).get("VOUCH_ADMIN_EMAILS", "")
    found |= {normalize_email(e) for e in raw.split(",") if e.strip()}
    if path is not None and path.is_file():
        found |= {normalize_email(line) for line in path.read_text(encoding="utf-8").splitlines()
                  if line.strip() and not line.lstrip().startswith("#")}
    return frozenset(found)


def _public(row: dict[str, Any]) -> dict[str, Any]:
    admin = bool(row["is_admin"])
    return {"id": row["id"], "email": row["email"], "name": row["name"], "is_admin": admin,
            "plan": row["plan"], "is_pro": admin or row["plan"] == "pro"}


class Throttle:
    """At most `limit` failures per key within `window` seconds (memory only)."""

    def __init__(self, limit: int, window: float, clock: Callable[[], float] = time.monotonic):
        self.limit, self.window, self.clock = limit, window, clock
        self.hits: dict[str, deque[float]] = {}
        self.lock = threading.Lock()

    def _recent(self, key: str) -> deque[float]:
        now = self.clock()
        hits = self.hits.setdefault(key, deque())
        while hits and now - hits[0] > self.window:
            hits.popleft()
        return hits

    def check(self, *keys: str) -> None:
        with self.lock:
            for key in keys:
                hits = self._recent(key)
                if len(hits) >= self.limit:
                    wait = max(1, int(self.window - (self.clock() - hits[0])) // 60 + 1)
                    raise AccountError(429, f"Too many attempts. Try again in {wait} minute"
                                            f"{'' if wait == 1 else 's'}.")

    def fail(self, *keys: str) -> None:
        with self.lock:
            for key in keys:
                self._recent(key).append(self.clock())

    def reset(self, *keys: str) -> None:
        with self.lock:
            for key in keys:
                self.hits.pop(key, None)


class Accounts:
    def __init__(self, db: Path | str, clock: Callable[[], float] = time.time,
                 admin_emails: Iterable[str] = ()) -> None:
        self.clock = clock
        self.admin_emails = frozenset(normalize_email(e) for e in admin_emails)
        self.url = str(db) if str(db).startswith(("postgres://", "postgresql://")) else None
        self.db_path = None if self.url else Path(db)
        if self.url:
            import psycopg  # the web layer's dependency; the engine never imports it
            self._pg = psycopg
            self._integrity = (psycopg.errors.UniqueViolation,)
        else:
            self._integrity = (sqlite3.IntegrityError,)
            self.db_path.parent.mkdir(parents=True, exist_ok=True)
            fresh = not self.db_path.exists()
            self._connect().close()
            if fresh:
                os.chmod(self.db_path, 0o600)  # profiles are personal: owner-only file
        self._create()
        self.login_throttle = Throttle(10, 15 * 60)
        self.signup_throttle = Throttle(20, 60 * 60)
        self._dummy_hash = hash_password(secrets.token_hex(8))

    @property
    def backend(self) -> str:
        return "postgres" if self.url else "sqlite"

    # -- storage ---------------------------------------------------------------
    def _connect(self):
        if self.url:
            from psycopg.rows import dict_row
            return self._pg.connect(self.url, row_factory=dict_row)
        conn = sqlite3.connect(self.db_path, timeout=10)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON")
        return conn

    def _run(self, sql: str, args: tuple = ()) -> list[dict[str, Any]]:
        if self.url:
            sql = sql.replace("?", "%s")
        conn = self._connect()
        try:
            with conn:
                cur = conn.execute(sql, args)
                rows = cur.fetchall() if cur.description else []
                return [dict(row) for row in rows]
        finally:
            conn.close()

    def _create(self) -> None:
        types = POSTGRES_TYPES if self.url else SQLITE_TYPES
        statements = [s.strip() for s in _TABLES.format(**types).split(";") if s.strip()]
        conn = self._connect()
        try:
            with conn:
                for statement in statements:
                    conn.execute(statement)
                for table, column, definition in MIGRATIONS:
                    if self.url:
                        conn.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} "
                                     f"{definition}")
                    elif column not in {r[1] for r in conn.execute(f"PRAGMA table_info({table})")}:
                        conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {definition}")
        finally:
            conn.close()

    # -- users ---------------------------------------------------------------
    def create_user(self, email: str, password: str, name: str = "") -> dict[str, Any]:
        email = normalize_email(email)
        name = (name or "").strip()
        if not EMAIL.match(email) or len(email) > EMAIL_MAX:
            raise AccountError(422, "Enter a valid email address.")
        if not PASSWORD_MIN <= len(password or "") <= PASSWORD_MAX:
            raise AccountError(422, f"Use a password of at least {PASSWORD_MIN} characters.")
        if password.strip().lower() == email:
            raise AccountError(422, "Your password can't be your email address.")
        if len(name) > NAME_MAX:
            raise AccountError(422, f"Keep your name under {NAME_MAX} characters.")
        try:
            self._run("INSERT INTO users (email, name, password_hash, is_admin, created_at) "
                      "VALUES (?, ?, ?, ?, ?)", (email, name, hash_password(password),
                                                 int(email in self.admin_emails), self.clock()))
        except self._integrity:
            raise AccountError(409, "An account with this email already exists. Log in "
                                    "instead.") from None
        return self.user_by_email(email)

    def user_by_email(self, email: str) -> dict[str, Any] | None:
        rows = self._run("SELECT * FROM users WHERE email = ?", (normalize_email(email),))
        return _public(rows[0]) if rows else None

    def user_by_id(self, user_id: int) -> dict[str, Any] | None:
        rows = self._run("SELECT * FROM users WHERE id = ?", (user_id,))
        return _public(rows[0]) if rows else None

    def authenticate(self, email: str, password: str) -> dict[str, Any] | None:
        rows = self._run("SELECT * FROM users WHERE email = ?", (normalize_email(email),))
        if not rows:
            check_password(password or "", self._dummy_hash)  # same work as a real check
            return None
        if not check_password(password or "", rows[0]["password_hash"]):
            return None
        if rows[0]["email"] in self.admin_emails and not rows[0]["is_admin"]:
            self._run("UPDATE users SET is_admin = 1 WHERE id = ?", (rows[0]["id"],))
            return self.user_by_id(rows[0]["id"])
        return _public(rows[0])

    def set_admin(self, email: str, admin: bool = True) -> dict[str, Any]:
        user = self.user_by_email(email)
        if user is None:
            raise AccountError(404, f"No account for {normalize_email(email)}; sign up first.")
        self._run("UPDATE users SET is_admin = ? WHERE id = ?", (int(admin), user["id"]))
        return self.user_by_email(email)

    def set_plan(self, user_id: int, plan: str) -> dict[str, Any]:
        if plan not in PLANS:
            raise AccountError(422, f"A plan is one of: {', '.join(PLANS)}.")
        if self.user_by_id(user_id) is None:
            raise AccountError(404, "No such account.")
        self._run("UPDATE users SET plan = ? WHERE id = ?", (plan, user_id))
        if plan == "pro":  # anything still waiting is now answered
            self._run("UPDATE pro_requests SET status = 'approved', decided_at = ? "
                      "WHERE user_id = ? AND status = 'pending'", (self.clock(), user_id))
        return self.user_by_id(user_id)

    def list_users(self) -> list[dict[str, Any]]:
        rows = self._run(
            "SELECT users.*, "
            "(SELECT COUNT(*) FROM profiles WHERE profiles.user_id = users.id) AS has_profile, "
            "(SELECT COUNT(*) FROM builds WHERE builds.user_id = users.id) AS builds, "
            "(SELECT COUNT(*) FROM pro_requests WHERE pro_requests.user_id = users.id "
            "AND pro_requests.status = 'pending') AS pending "
            "FROM users ORDER BY created_at DESC")
        return [{**_public(r), "created_at": r["created_at"], "has_profile": bool(r["has_profile"]),
                 "builds": r["builds"], "pending_request": bool(r["pending"])} for r in rows]

    def delete_user(self, user_id: int) -> None:
        self._run("DELETE FROM users WHERE id = ?", (user_id,))  # everything else cascades

    # -- sessions ------------------------------------------------------------
    def create_session(self, user_id: int) -> str:
        token = secrets.token_urlsafe(32)
        now = self.clock()
        self._run("DELETE FROM sessions WHERE expires_at < ?", (now,))
        self._run("INSERT INTO sessions (token_hash, user_id, created_at, expires_at) "
                  "VALUES (?, ?, ?, ?)", (_token_hash(token), user_id, now, now + SESSION_SECONDS))
        return token

    def user_for_session(self, token: str | None) -> dict[str, Any] | None:
        if not token or len(token) > 200:
            return None
        rows = self._run("SELECT users.* FROM sessions JOIN users ON users.id = sessions.user_id "
                         "WHERE sessions.token_hash = ? AND sessions.expires_at > ?",
                         (_token_hash(token), self.clock()))
        return _public(rows[0]) if rows else None

    def end_session(self, token: str | None) -> None:
        if token:
            self._run("DELETE FROM sessions WHERE token_hash = ?", (_token_hash(token),))

    # -- profiles and resume headers ---------------------------------------------
    def save_profile(self, user_id: int, filename: str, content: bytes) -> dict[str, Any]:
        sha = hashlib.sha256(content).hexdigest()
        self._run("INSERT INTO profiles (user_id, filename, content, sha256, updated_at) "
                  "VALUES (?, ?, ?, ?, ?) ON CONFLICT (user_id) DO UPDATE SET "
                  "filename = excluded.filename, content = excluded.content, "
                  "sha256 = excluded.sha256, updated_at = excluded.updated_at",
                  (user_id, Path(filename).name, content, sha, self.clock()))
        return self.profile(user_id)

    def profile(self, user_id: int) -> dict[str, Any] | None:
        rows = self._run("SELECT filename, content, sha256, updated_at FROM profiles "
                         "WHERE user_id = ?", (user_id,))
        if not rows:
            return None
        row = rows[0]
        return {"filename": row["filename"], "content": bytes(row["content"]),
                "sha256": row["sha256"], "updated_at": row["updated_at"]}

    def delete_profile(self, user_id: int) -> None:
        self._run("DELETE FROM profiles WHERE user_id = ?", (user_id,))

    def save_header(self, user_id: int, header: dict[str, Any]) -> dict[str, Any]:
        self._run("INSERT INTO resume_headers (user_id, header, updated_at) VALUES (?, ?, ?) "
                  "ON CONFLICT (user_id) DO UPDATE SET header = excluded.header, "
                  "updated_at = excluded.updated_at", (user_id, json.dumps(header), self.clock()))
        return header

    def header(self, user_id: int) -> dict[str, Any] | None:
        rows = self._run("SELECT header FROM resume_headers WHERE user_id = ?", (user_id,))
        return json.loads(rows[0]["header"]) if rows else None

    # -- Pro requests ------------------------------------------------------------
    def request_pro(self, user_id: int, note: str = "") -> dict[str, Any]:
        note = (note or "").strip()
        if len(note) > NOTE_MAX:
            raise AccountError(422, f"Keep the note under {NOTE_MAX} characters.")
        user = self.user_by_id(user_id)
        if user is None:
            raise AccountError(404, "No such account.")
        if user["is_pro"]:
            raise AccountError(409, "Your account already has Pro.")
        pending = self.pending_request(user_id)
        if pending is not None:
            return pending
        self._run("INSERT INTO pro_requests (user_id, note, status, created_at) "
                  "VALUES (?, ?, 'pending', ?)", (user_id, note, self.clock()))
        return self.pending_request(user_id)

    def pending_request(self, user_id: int) -> dict[str, Any] | None:
        rows = self._run("SELECT * FROM pro_requests WHERE user_id = ? AND status = 'pending' "
                         "ORDER BY id DESC", (user_id,))
        return rows[0] if rows else None

    def latest_request(self, user_id: int) -> dict[str, Any] | None:
        rows = self._run("SELECT * FROM pro_requests WHERE user_id = ? ORDER BY id DESC",
                         (user_id,))
        return rows[0] if rows else None

    def list_requests(self, status: str | None = "pending") -> list[dict[str, Any]]:
        sql = ("SELECT pro_requests.*, users.email, users.name, users.plan FROM pro_requests "
               "JOIN users ON users.id = pro_requests.user_id")
        args: tuple = ()
        if status:
            sql += " WHERE pro_requests.status = ?"
            args = (status,)
        return self._run(sql + " ORDER BY pro_requests.created_at DESC", args)

    def decide_request(self, request_id: int, approve: bool, admin_id: int) -> dict[str, Any]:
        rows = self._run("SELECT * FROM pro_requests WHERE id = ?", (request_id,))
        if not rows:
            raise AccountError(404, "No such request.")
        if rows[0]["status"] != "pending":
            raise AccountError(409, f"This request was already {rows[0]['status']}.")
        self._run("UPDATE pro_requests SET status = ?, decided_at = ?, decided_by = ? WHERE id = ?",
                  ("approved" if approve else "declined", self.clock(), admin_id, request_id))
        if approve:
            self._run("UPDATE users SET plan = 'pro' WHERE id = ?", (rows[0]["user_id"],))
        return self._run("SELECT * FROM pro_requests WHERE id = ?", (request_id,))[0]

    # -- Pro builds ----------------------------------------------------------------
    def save_build(self, user_id: int, job_id: str, title: str, company: str, status: str,
                   summary: dict[str, Any], pdf: bytes | None, report: str | None) -> None:
        self._run("INSERT INTO builds (user_id, job_id, title, company, status, summary, pdf, "
                  "report, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?) "
                  "ON CONFLICT (user_id, job_id) DO UPDATE SET title = excluded.title, "
                  "company = excluded.company, status = excluded.status, "
                  "summary = excluded.summary, pdf = excluded.pdf, report = excluded.report, "
                  "created_at = excluded.created_at",
                  (user_id, job_id, title, company, status, json.dumps(summary), pdf, report,
                   self.clock()))

    def builds(self, user_id: int) -> list[dict[str, Any]]:
        rows = self._run("SELECT job_id, title, company, status, summary, created_at, "
                         "pdf IS NOT NULL AS has_pdf FROM builds WHERE user_id = ? "
                         "ORDER BY created_at DESC", (user_id,))
        return [{**r, "summary": json.loads(r["summary"]), "has_pdf": bool(r["has_pdf"])}
                for r in rows]

    def build(self, user_id: int, job_id: str) -> dict[str, Any] | None:
        rows = self._run("SELECT * FROM builds WHERE user_id = ? AND job_id = ?",
                         (user_id, job_id))
        if not rows:
            return None
        row = rows[0]
        return {**row, "summary": json.loads(row["summary"]),
                "pdf": bytes(row["pdf"]) if row["pdf"] is not None else None}
