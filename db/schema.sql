-- VouchStudio on Neon (serverless Postgres). Applied by `npm run db:migrate`, which every
-- Vercel build runs first (see package.json "vercel-build"). Every statement is idempotent
-- and additive: it never drops or rewrites data.
--
-- Accounts: the same tables accounts.py creates, so the hosted app and the local Studio
-- (server.py with DATABASE_URL set to this database) share users, sessions and plans.
-- Timestamps there are epoch seconds (DOUBLE PRECISION), as accounts.py writes them.
-- tests/test_hosting.py checks that every accounts.py table and column is defined here.

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL DEFAULT '',
    password_hash TEXT NOT NULL,
    is_admin INTEGER NOT NULL DEFAULT 0,
    plan TEXT NOT NULL DEFAULT 'basic',
    created_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at DOUBLE PRECISION NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL
);
-- The uploaded resume or master profile. With R2 the file is the object at object_key
-- (users/<id>/profile/<sha256><ext>) and content is empty.
CREATE TABLE IF NOT EXISTS profiles (
    user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    content BYTEA NOT NULL,
    sha256 TEXT NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS resume_headers (
    user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    header TEXT NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS pro_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    note TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'pending',
    created_at DOUBLE PRECISION NOT NULL,
    decided_at DOUBLE PRECISION,
    decided_by INTEGER
);
-- Pro builds. The hosted app queues them (status 'queued'); `server.py --process-builds`
-- runs them where LaTeX is installed and stores the PDF in R2 at pdf_key.
CREATE TABLE IF NOT EXISTS builds (
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    job_id TEXT NOT NULL,
    title TEXT NOT NULL DEFAULT '',
    company TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL,
    summary TEXT NOT NULL,
    pdf BYTEA,
    report TEXT,
    created_at DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (user_id, job_id)
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS plan TEXT NOT NULL DEFAULT 'basic';
ALTER TABLE profiles ADD COLUMN IF NOT EXISTS object_key TEXT;
ALTER TABLE builds ADD COLUMN IF NOT EXISTS pdf_key TEXT;
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions (expires_at);
CREATE INDEX IF NOT EXISTS builds_status ON builds (status, created_at);

-- Log-in and sign-up throttling (the hosted app has no long-lived process to count in).
CREATE TABLE IF NOT EXISTS auth_attempts (
    key TEXT NOT NULL,
    at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS auth_attempts_key ON auth_attempts (key, at);

-- The board: published from the local index by scripts/publish-jobs.mjs. board.value for
-- key 'index' names the requirements-only index in R2 that api/engine.py scores against.
CREATE TABLE IF NOT EXISTS board (
    key TEXT PRIMARY KEY,
    value JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS jobs (
    id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    company TEXT NOT NULL DEFAULT '',
    source TEXT NOT NULL DEFAULT 'Manual',
    location TEXT NOT NULL DEFAULT 'Not specified',
    region TEXT NOT NULL DEFAULT '',
    url TEXT,
    posted TEXT,
    complete BOOLEAN NOT NULL DEFAULT TRUE,
    level TEXT NOT NULL,
    domain TEXT,
    skill_requirements INTEGER NOT NULL DEFAULT 0,
    enough_detail BOOLEAN NOT NULL DEFAULT FALSE,
    description TEXT NOT NULL DEFAULT '',
    sha256 TEXT NOT NULL,
    published_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS jobs_company ON jobs (lower(company));
CREATE INDEX IF NOT EXISTS jobs_posted ON jobs (posted DESC NULLS LAST);

-- Each account's board scores, from api/engine.py. A run is stale when the profile or the
-- published index changes (its SHA-256s differ), and the next board load rescores.
CREATE TABLE IF NOT EXISTS score_runs (
    user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    profile_sha256 TEXT NOT NULL,
    index_sha256 TEXT NOT NULL,
    summary JSONB NOT NULL,
    scored_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS job_scores (
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    job_id TEXT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
    score INTEGER,
    rank INTEGER,
    verdict TEXT,
    insufficient BOOLEAN NOT NULL DEFAULT FALSE,
    requirements INTEGER NOT NULL DEFAULT 0,
    skill_requirements INTEGER NOT NULL DEFAULT 0,
    matched JSONB NOT NULL DEFAULT '[]',
    gaps JSONB NOT NULL DEFAULT '[]',
    recognized JSONB NOT NULL DEFAULT '[]',
    PRIMARY KEY (user_id, job_id)
);

-- Reviews: what people say about a company or one of its postings. Text and links live
-- here; images, PDFs and videos are R2 objects under users/<id>/reviews/, uploaded straight
-- from the browser with presigned URLs and tracked in review_media.
CREATE TABLE IF NOT EXISTS reviews (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    company TEXT NOT NULL,
    job_id TEXT REFERENCES jobs(id) ON DELETE SET NULL,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    title TEXT NOT NULL,
    body TEXT NOT NULL,
    links JSONB NOT NULL DEFAULT '[]',
    status TEXT NOT NULL DEFAULT 'published' CHECK (status IN ('published', 'hidden')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS reviews_company ON reviews (lower(company), created_at DESC);
CREATE INDEX IF NOT EXISTS reviews_job ON reviews (job_id);
CREATE INDEX IF NOT EXISTS reviews_user ON reviews (user_id);

CREATE TABLE IF NOT EXISTS review_media (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    review_id INTEGER REFERENCES reviews(id) ON DELETE CASCADE,
    object_key TEXT NOT NULL UNIQUE,
    kind TEXT NOT NULL CHECK (kind IN ('image', 'pdf', 'video')),
    content_type TEXT NOT NULL,
    size_bytes BIGINT NOT NULL,
    filename TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'ready')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS review_media_review ON review_media (review_id);
CREATE INDEX IF NOT EXISTS review_media_pending ON review_media (status, created_at);
